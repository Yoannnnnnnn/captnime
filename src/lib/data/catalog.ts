interface EpisodeOptions {
  count: number;
  /** Selisih hari antara dua episode. */
  interval: number;
  /** Episode terakhir dirilis berapa hari lalu (0 = hari ini). */
  lastReleasedDaysAgo: number;
  duration: number;
  titles?: string[];
  fillers?: number[];
  seed?: number;
}

function makeEpisodes({
  count,
  interval,
  lastReleasedDaysAgo,
  duration,
  titles = [],
  fillers = [],
  seed = 0,
}: EpisodeOptions): Episode[] {
  return Array.from({ length: count }, (_, i) => {
    const number = i + 1;
    const released = ANCHOR - (lastReleasedDaysAgo + (count - number) * interval) * DAY;
    return {
      number,
      title: titles[i] ?? `Episode ${number}`,
      duration,
      releasedAt: new Date(released).toISOString(),
      synopsis: undefined,
      servers: buildServers(seed + number),
      subtitles: DEFAULT_SUBTITLES.map((s) => ({ ...s })),
      filler: fillers.includes(number),
    };
  });
}

